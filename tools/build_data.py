#!/usr/bin/env python3
"""Generate worker/zips.js from zipcodes.db.

Zip codes repeat (81,831 rows, 42,522 zips). The old PHP ran `... WHERE zipcode='$zip' LIMIT 1`
with no ORDER BY, which SQLite answers with the lowest rowid, so the first row by id wins here too.
"""
import sqlite3
from pathlib import Path

root = Path(__file__).resolve().parent.parent
db = sqlite3.connect(root / "zipcodes.db")
seen, lines = set(), []
for zipcode, country, state, city in db.execute("SELECT zipcode, country, state, city FROM zipcodes ORDER BY id"):
    if zipcode in seen:
        continue
    seen.add(zipcode)
    for field in (country, state, city):
        assert "|" not in field and "\n" not in field and "`" not in field and "${" not in field
    lines.append(f"{zipcode}|{country}|{state}|{city}")
(root / "worker" / "zips.js").write_text(
    "// Generated by tools/build_data.py from zipcodes.db. zip|country|state|city, first row per zip.\n"
    "export default `" + "\n".join(lines) + "`;\n")
print(len(lines), "zips")
